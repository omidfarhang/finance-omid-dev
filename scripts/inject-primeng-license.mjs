#!/usr/bin/env node
/**
 * Writes apps/web/src/environments/license.local.ts from PRIMENG_LICENSE
 * (env var or root .env). Safe to run repeatedly; file is gitignored.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(
  root,
  'apps/web/src/environments/license.local.ts',
);

function readRootEnv(name) {
  if (process.env[name]) return process.env[name];
  const envPath = path.join(root, '.env');
  if (!fs.existsSync(envPath)) return '';
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    if (key !== name) continue;
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    return value;
  }
  return '';
}

const license = readRootEnv('PRIMENG_LICENSE');
const contents = `/** Generated by scripts/inject-primeng-license.mjs — do not edit or commit. */
export const primeNgLicense = ${JSON.stringify(license)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, contents);
console.log(
  license
    ? `Wrote PrimeNG license to ${path.relative(root, outFile)}`
    : `Wrote empty PrimeNG license to ${path.relative(root, outFile)} (set PRIMENG_LICENSE in .env)`,
);
